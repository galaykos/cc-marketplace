  function cbody(l,   s) {
    s = l
    sub(/^[ \t]+/, "", s)
    if (s ~ /^#!/) return ""
    if (s ~ /^\/\//)  { sub(/^\/\/+[ \t]*/, "", s); return s }
    if (s ~ /^\/\*/)  { sub(/^\/\*+[ \t]*/, "", s); sub(/[ \t]*\*\/[ \t]*$/, "", s); return s }
    if (s ~ /^\*/ && s !~ /^\*[A-Za-z0-9_(]/) { sub(/^\*+[ \t]*/, "", s); sub(/[ \t]*\*\/[ \t]*$/, "", s); return s }
    if (s ~ /^#[ \t]/ || s ~ /^##/) { sub(/^#+[ \t]*/, "", s); return s }
    if (s ~ /^-- /)   { sub(/^--[ \t]*/, "", s); return s }
    return ""
  }
