  function is_banner(b,   c) {
    if (b !~ /^[=*#_~-][=*#_~-][=*#_~-]/ && b !~ /[=*#_~-][=*#_~-][=*#_~-][ \t]*$/) return 0
    c = b
    gsub(/[^A-Za-z0-9]/, "", c)
