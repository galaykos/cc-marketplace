"""Writes skills/pipeline/references/forge-api.md from the forge sources (signature + first docstring sentence).
--check exits 1 when the committed file differs, so a changed signature cannot leave the skill's reference stale."""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "blender_lib" / "forge"
OUT = ROOT / "skills" / "pipeline" / "references" / "forge-api.md"
ORDER = ["blockout", "deform", "retopo", "uv", "lod", "collision", "retarget", "util",
         "bake", "stylize", "project_paint", "review_renders", "validate", "export"]
LIVE = {"blockout", "deform", "retopo", "uv", "lod", "collision", "retarget", "util"}
LIVE_FUNCTIONS = {"stylize.apply_albedo"}
ABBREVIATIONS = ("e.g.", "i.e.", "etc.", "vs.")


def first_sentence(doc):
    """The docstring's first sentence without its full stop: ends at '. ' outside brackets and abbreviations."""
    text = doc.strip().split("\n\n")[0].replace("\n", " ")
    depth = 0
    for i, ch in enumerate(text):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth = max(0, depth - 1)
        elif (ch == "." and depth == 0 and text[i + 1:i + 2] in ("", " ")
              and not text[:i + 1].endswith(ABBREVIATIONS)):
            return text[:i]
    return text.rstrip(".")


def render():
    out = ["# forge API", "",
           "Generated by `scripts/gen_forge_api.py` from the module sources (signature + first docstring sentence).",
           "Live modules run through `execute_blender_code` after the import snippet; headless ones are reached",
           "through the forge MCP tools (`validate_asset`, `bake_maps`, …) or `batch_run`. Distances are metres.", ""]
    for name in ORDER:
        tree = ast.parse((LIB / f"{name}.py").read_text(encoding="utf-8"))
        out += [f"## {name} ({'live' if name in LIVE else 'headless, via the MCP tools'})", ""]
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                line = f"- `{node.name}({ast.unparse(node.args)})`"
                if f"{name}.{node.name}" in LIVE_FUNCTIONS:
                    line += " (live)"
                doc = first_sentence(ast.get_docstring(node) or "")
                out.append(f"{line} — {doc}." if doc else line)
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT.relative_to(ROOT)} — run python3 scripts/gen_forge_api.py")
            sys.exit(1)
        print("forge-api.md is current")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
